import type { Player, TeamLineup } from "../types";

type Listing = readonly [number, string];

function players(list: readonly Listing[]): Player[] {
  return list.map(([number, name]) => ({ number, name }));
}

function lineup(
  matchId: string,
  teamId: string,
  starters: readonly Listing[],
  subs: readonly Listing[],
  source: string,
): TeamLineup {
  return {
    matchId,
    teamId,
    starters: players(starters),
    subs: players(subs),
    source,
  };
}

